CREATE TABLE IF NOT EXISTS `zoomcamp-e-commerce.ecommerce_raw_data.customers`
(
  unique_row_id BYTES OPTIONS (description = 'A unique identifier for the customer, generated by hashing key customers attributes.'),
  customer_id STRING OPTIONS (description = 'key to the orders dataset. Each order has a unique customer_id.'),
  customer_unique_id STRING OPTIONS (description = 'unique identifier of a customer.'),
  customer_zip_code_prefix STRING OPTIONS (description = 'first five digits of customer zip code'),
  customer_city STRING OPTIONS (description = 'customer city name'),
  customer_state STRING OPTIONS (description = 'customer state')
)
CLUSTER BY customer_id, customer_unique_id;

CREATE OR REPLACE EXTERNAL TABLE `zoomcamp-e-commerce.ecommerce_raw_data.customers_ext`
(
  customer_id STRING OPTIONS (description = 'key to the orders dataset. Each order has a unique customer_id.'),
  customer_unique_id STRING OPTIONS (description = 'unique identifier of a customer.'),
  customer_zip_code_prefix STRING OPTIONS (description = 'first five digits of customer zip code'),
  customer_city STRING OPTIONS (description = 'customer city name'),
  customer_state STRING OPTIONS (description = 'customer state')
)
OPTIONS (
  format = 'CSV',
  uris = ['gs://bs-e-commerce_data/olist_customers_dataset.csv']
);


CREATE OR REPLACE TABLE `zoomcamp-e-commerce.ecommerce_raw_data.customers_temp`
AS
  SELECT MD5(CONCAT(
      COALESCE(CAST(customer_id AS STRING), ""),
      COALESCE(CAST(customer_unique_id AS STRING), "")
  )) AS unique_row_id,
    *
  FROM `zoomcamp-e-commerce.ecommerce_raw_data.customers_ext`;
  
MERGE INTO `zoomcamp-e-commerce.ecommerce_raw_data.customers` T
  USING `zoomcamp-e-commerce.ecommerce_raw_data.customers_temp` S
  ON T.unique_row_id = S.unique_row_id
  WHEN NOT MATCHED THEN
    INSERT (unique_row_id, customer_id,customer_unique_id,customer_zip_code_prefix,customer_city,customer_state)
            VALUES (S.unique_row_id, S.customer_id, S.customer_unique_id, S.customer_zip_code_prefix, S.customer_city, S.customer_state);