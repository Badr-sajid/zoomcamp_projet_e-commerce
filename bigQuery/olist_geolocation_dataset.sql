CREATE TABLE IF NOT EXISTS `zoomcamp-e-commerce.ecommerce_raw_data.geolocations`
(
  unique_row_id BYTES OPTIONS (description = 'A unique identifier for the geolocation, generated by hashing key geolocations attributes.'),
  geolocation_zip_code_prefix NUMERIC OPTIONS (description = 'first 5 digits of zip code.'),
  geolocation_lat NUMERIC OPTIONS (description = 'latitude.'),
  geolocation_lng NUMERIC OPTIONS (description = 'longitude.'),
  geolocation_city STRING OPTIONS (description = 'city name.'),
  geolocation_state STRING OPTIONS (description = 'state.')
)
CLUSTER BY geolocation_lat, geolocation_lng;

CREATE OR REPLACE EXTERNAL TABLE `zoomcamp-e-commerce.ecommerce_raw_data.geolocations_ext`
(
  geolocation_zip_code_prefix NUMERIC OPTIONS (description = 'first 5 digits of zip code.'),
  geolocation_lat NUMERIC OPTIONS (description = 'latitude.'),
  geolocation_lng NUMERIC OPTIONS (description = 'longitude.'),
  geolocation_city STRING OPTIONS (description = 'city name.'),
  geolocation_state STRING OPTIONS (description = 'state.')
)
OPTIONS (
  format = 'CSV',
  uris = ['gs://bs-e-commerce_data/olist_geolocation_dataset.csv']
);


CREATE OR REPLACE TABLE `zoomcamp-e-commerce.ecommerce_raw_data.geolocations_temp`
AS
  SELECT MD5(CONCAT(
      COALESCE(CAST(geolocation_lat AS NUMERIC), ""),
      COALESCE(CAST(geolocation_lng AS NUMERIC), "")
  )) AS unique_row_id,
    *
  FROM `zoomcamp-e-commerce.ecommerce_raw_data.geolocations_ext`;
  
MERGE INTO `zoomcamp-e-commerce.ecommerce_raw_data.geolocations` T
  USING `zoomcamp-e-commerce.ecommerce_raw_data.geolocations_temp` S
  ON T.unique_row_id = S.unique_row_id
  WHEN NOT MATCHED THEN
    INSERT (unique_row_id, geolocation_zip_code_prefix, geolocation_lat, geolocation_lng, geolocation_city, geolocation_state)
            VALUES (S.unique_row_id, S.geolocation_zip_code_prefix, S.geolocation_lat, S.geolocation_lng, S.geolocation_city, S.geolocation_state);
